// Regenerates src/local/mlx-lock.ts: the exact packages the MLX engine installs, each with the
// sha256 of every Apple Silicon wheel PyPI publishes for it, so `pip install --require-hashes`
// refuses anything else. Run after bumping MLX_LM below, then commit the result.
//   bun scripts/mlx-lock.ts
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const MLX_LM = "0.32.2";
const PY = "3.12";

const work = mkdtempSync(join(tmpdir(), "niti-mlx-lock-"));
try {
  const venv = join(work, "v");
  if (Bun.spawnSync(["python3", "-m", "venv", venv]).exitCode !== 0) throw new Error("python3 -m venv failed");
  const report = join(work, "report.json");
  const r = Bun.spawnSync([join(venv, "bin/pip"), "install", "--dry-run", "--ignore-installed", "--report", report, "--only-binary=:all:", "--platform", "macosx_14_0_arm64", "--python-version", PY, "--implementation", "cp", "--target", join(work, "t"), `mlx-lm==${MLX_LM}`]);
  if (r.exitCode !== 0) throw new Error(`resolve failed: ${r.stderr}`);
  const pkgs = (JSON.parse(readFileSync(report, "utf8")).install as { metadata: { name: string; version: string } }[]).map((i) => i.metadata);
  const cp = PY.replace(".", "");
  const fits = (fn: string) => {
    if (/py2?\.?py3-none-any\.whl$/.test(fn) || fn.endsWith("py3-none-any.whl")) return true;
    if (!/arm64|universal2/.test(fn)) return false;
    const [py, abi] = fn.split("-").slice(-3, -1) as [string, string];
    if (py.includes(`cp${cp}`) && (abi === `cp${cp}` || abi === "abi3" || abi === "none")) return true;
    const v = /^cp3(\d+)/.exec(py);
    return (abi === "abi3" && !!v && Number(v[1]) <= Number(cp.slice(1))) || (py.startsWith("py3") && abi === "none");
  };
  const lines: string[] = [];
  for (const p of pkgs) {
    const d = (await (await fetch(`https://pypi.org/pypi/${p.name}/${p.version}/json`)).json()) as { urls: { filename: string; packagetype: string; digests: { sha256: string } }[] };
    const hashes = [...new Set(d.urls.filter((f) => f.packagetype === "bdist_wheel" && fits(f.filename)).map((f) => f.digests.sha256))].sort();
    if (!hashes.length) throw new Error(`no Apple Silicon wheel for ${p.name} ${p.version}`);
    lines.push(`${p.name}==${p.version} ${hashes.map((h) => `--hash=sha256:${h}`).join(" ")}`);
  }
  writeFileSync(
    join(import.meta.dir, "../src/local/mlx-lock.ts"),
    `// Generated by scripts/mlx-lock.ts — do not edit by hand. mlx-lm ${MLX_LM} and everything it needs,\n` +
      `// pinned to exact versions and the sha256 of every Apple Silicon wheel, for pip --require-hashes.\n` +
      `export const MLX_LM_VERSION = "${MLX_LM}";\n\nexport const MLX_REQUIREMENTS = [\n${lines.map((l) => `  ${JSON.stringify(l)},`).join("\n")}\n].join("\\n");\n`,
  );
  console.log(`src/local/mlx-lock.ts: ${lines.length} packages`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
